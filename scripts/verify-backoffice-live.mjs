async function signIn(role, returnTo) {
  if (!local[`DEMO_${role}_PASSWORD`]) throw Error("Demo credential missing in ignored local env");
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } }); contexts.push(context);
  const page = await context.newPage(); page.setDefaultTimeout(30_000);
  const destination = returnTo ? `/sign-in?returnTo=${encodeURIComponent(returnTo)}` : "/sign-in";
  await page.goto(app + destination);
  await page.getByRole("button", { name: "Continue to sign in", exact: true }).click();
  await page.waitForURL((url) => url.pathname.includes("/realms/nexus/protocol/openid-connect/auth"));
  await page.locator("#username").fill(`${role.toLowerCase()}@nexus.local`);
  await page.locator("#password").fill(local[`DEMO_${role}_PASSWORD`]);
  await page.locator("#kc-login").click();
  await page.waitForURL(`${app}${returnTo || (role === "BUYER" ? "/" : "/backoffice")}`, { timeout: 60_000 });
  return page;
}
async function mutation(page, method, endpoint, action, status) {
  const pending = page.waitForResponse((response) => new URL(response.url()).pathname === endpoint && response.request().method() === method);
  await action(); const response = await pending;
  const operation = { method, path: endpoint, status: response.status() };
  if (method === "POST" && endpoint.endsWith("/skus") || method === "PUT" && endpoint.startsWith("/api/v1/skus/")) {
    const payload = response.request().postDataJSON();
    operation.bodyFieldNames = Object.keys(payload);
    if (Object.hasOwn(payload, "skuCode")) throw Error("SKU code must be generated by the server");
  }
  let body;
  if (response.status() !== 204) { body = await response.json(); operation.applicationCode = body.code; }
  report.operations.push(operation);
  if (response.status() !== status || body && body.code !== 0) throw Error("Unexpected business response");
  return body?.data;
}
