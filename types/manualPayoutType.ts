import type { components } from "./paymentGeneratedType";
import type { PayoutStatus } from "./payoutType";
import type { DisputeStatus, ReceiptStatus } from "./payoutReceiptType";

type Schemas = components["schemas"];

export const manualAttemptStates = ["CLAIMED", "QR_ISSUED", "SUCCEEDED", "NOT_SENT", "UNKNOWN", "RETURNED", "CONFIRMATION_CORRECTED"] as const satisfies readonly Schemas["ManualPayoutAttemptState"][];
export type ManualAttemptState = Schemas["ManualPayoutAttemptState"];
export const manualPayoutActions = ["READINESS_CHECK", "CLAIM", "ISSUE_QR", "READ_QR", "RELEASE", "UPLOAD_EVIDENCE", "CONFIRM_TRANSFER", "REPORT_PROBLEM", "RESOLVE", "REVIEW_DISPUTE", "RETRY"] as const satisfies readonly Schemas["ManualPayoutAction"][];
export type ManualPayoutAction = typeof manualPayoutActions[number];
export const manualCapabilityActions = ["EXECUTE", "RECONCILE"] as const satisfies readonly Schemas["ManualPayoutCapabilities"]["allowedActions"][number][];
export const manualResolutionOutcomes = ["CONFIRMED_SENT", "CONFIRMED_NOT_SENT", "CONFIRMED_RETURNED", "CONFIRMATION_RECORDED_IN_ERROR"] as const satisfies readonly Schemas["ManualPayoutResolutionRequest"]["outcome"][];
export type ManualResolutionOutcome = Schemas["ManualPayoutResolutionRequest"]["outcome"];
export const disputeReviewActions = ["REQUEST_INFORMATION", "TRANSFER_EVIDENCE_PROVIDED"] as const satisfies readonly Schemas["ManualPayoutReviewRequest"]["action"][];
export type DisputeReviewAction = Schemas["ManualPayoutReviewRequest"]["action"];
export const manualCaseKinds = ["SELLER_DISPUTE", "STAFF_EXCEPTION"] as const satisfies readonly Schemas["ManualPayoutCaseView"]["kind"][];
export type ManualCaseKind = Schemas["ManualPayoutCaseView"]["kind"];
export const evidenceContentTypes = ["image/jpeg", "image/png", "application/pdf"] as const satisfies readonly Schemas["ManualPayoutEvidenceView"]["contentType"][];
export type EvidenceContentType = Schemas["ManualPayoutEvidenceView"]["contentType"];
export const maxEvidenceBytes = 10 * 1024 * 1024;
export const maxEvidenceFiles = 3;

export type SourceAccount = Schemas["ManualPayoutCapabilities"]["sourceAccounts"][number];
export type ManualPayoutCapabilities = {
  enabled: boolean;
  executionMode: "AUTO" | "MANUAL";
  automaticJobsEnabled: boolean;
  serverTime: string;
  sourceAccounts: SourceAccount[];
  canExecute: boolean;
  canReconcile: boolean;
};
export type ManualRecipient = NonNullable<Schemas["ManualPayoutView"]["recipient"]>;
export type ManualEvidence = Schemas["ManualPayoutEvidenceView"];
export type ManualAttempt = Omit<NonNullable<Schemas["ManualPayoutAttemptView"]>, "state" | "receiptStatus"> & { state: ManualAttemptState; receiptStatus: ReceiptStatus };
export type ManualCase = Omit<Schemas["ManualPayoutCaseView"], "status" | "explanation"> & { status: DisputeStatus; explanation: string };
export type ManualHistoryEntry = Schemas["ManualPayoutHistoryView"];
export type ManualPayout = {
  id: string;
  orderId: string;
  sellerId: string;
  status: PayoutStatus;
  executionMode: "MANUAL";
  confirmationSource: "MANUAL_STAFF_CONFIRMED" | null;
  orderAmount: string;
  shippingFee: string;
  platformFee: string;
  netAmount: string;
  currency: string;
  version: number;
  blockedReason: string | null;
  allowedActions: ManualPayoutAction[];
  serverTime: string;
  createdAt: string;
  updatedAt: string;
  currentAttempt: ManualAttempt | null;
  evidence: ManualEvidence[];
  cases: ManualCase[];
  history: ManualHistoryEntry[];
  recipient: ManualRecipient | null;
  openCases: ManualCase[];
  openSellerDispute: ManualCase | null;
  needsReview: boolean;
};
export type ManualPayoutFilters = {
  sellerId?: string;
  status?: readonly PayoutStatus[];
  claimedBy?: "me";
  receiptStatus?: ReceiptStatus;
  hasOpenDispute?: boolean;
  needsReview?: boolean;
  from?: string;
  to?: string;
  page?: number;
  size?: number;
};
export type ManualConfirmationInput = Omit<Schemas["ManualPayoutConfirmationRequest"], "expectedAttemptVersion">;
export type ManualProblemInput = { reason: string; evidenceIds: string[] };
export type ManualResolutionInput = Omit<Schemas["ManualPayoutResolutionRequest"], "expectedPayoutVersion" | "expectedAttemptVersion">;
export type DisputeReviewInput = { action: DisputeReviewAction; reason: string; evidenceIds: string[]; expectedCaseVersion: number };
export type ManualCommand<T = undefined> = { idempotencyKey: string; expectedVersion: number; body?: T };
export type ManualResolutionCommand = { idempotencyKey: string; expectedPayoutVersion: number; expectedAttemptVersion: number; body: ManualResolutionInput };
